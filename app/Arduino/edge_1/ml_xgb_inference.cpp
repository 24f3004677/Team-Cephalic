bool runMLXGB(
    const float features[ML_XGB_FEATURES],
    MLXGBResult &result)
{
    if (!features) return false;

    float margin[ML_XGB_CLASSES] = {
        1.070602f,
        -0.29125404f,
        -0.77934813f
    };

    for (int t = 0; t < ML_XGB_TREES; ++t)
    {
        const int start = ML_TREE_OFFSETS[t];
        const int end   = ML_TREE_OFFSETS[t + 1];
        int node = 0;
        float leafValue = 0.0f;

        while (true)
        {
            const int g = start + node;
            const int8_t lch = ML_LEFT[g];

            // Leaf node
            if (lch < 0)
            {
                leafValue = ML_LEAF[g];
                break;
            }

            const uint8_t f = ML_FEATURE[g];
            const float x = features[f];

            int nextNode;

            // XGBoost learned default direction for missing values.
            if (isnan(x))
            {
                nextNode = ML_DEFAULT_LEFT[g]
                         ? ML_LEFT[g]
                         : ML_RIGHT[g];
            }
            else if (x < ML_SPLIT[g])
            {
                nextNode = ML_LEFT[g];
            }
            else
            {
                nextNode = ML_RIGHT[g];
            }

            if (nextNode < 0 || start + nextNode >= end)
                return false;

            node = nextNode;
        }

        const uint8_t cls = ML_TREE_CLASS[t];
        if (cls >= ML_XGB_CLASSES)
            return false;

        margin[cls] += leafValue;
    }

    result.margin[0] = margin[0];
    result.margin[1] = margin[1];
    result.margin[2] = margin[2];

    // Exact softmax, numerically stable.
    float maxMargin = margin[0];
    if (margin[1] > maxMargin) maxMargin = margin[1];
    if (margin[2] > maxMargin) maxMargin = margin[2];

    const float e0 = expf(margin[0] - maxMargin);
    const float e1 = expf(margin[1] - maxMargin);
    const float e2 = expf(margin[2] - maxMargin);
    const float sum = e0 + e1 + e2;

    if (!(sum > 0.0f) || !isfinite(sum))
        return false;

    result.probability[0] = e0 / sum;
    result.probability[1] = e1 / sum;
    result.probability[2] = e2 / sum;

    uint8_t best = 0;
    if (result.probability[1] > result.probability[best]) best = 1;
    if (result.probability[2] > result.probability[best]) best = 2;

    result.predictionClass = best;

    return true;
}
