static inline float sigmoidStable(float x) {
  if (x >= 0.0f) {
    float e = expf(-x);
    return 1.0f / (1.0f + e);
  }
  float e = expf(x);
  return e / (1.0f + e);
}

bool runXGBEnsemble(const float features[XGB_ENSEMBLE_FEATURES], XGBEnsembleResult &result) {
  // XGBoost JSON base_score = 0.43333334 for binary:logistic.
  // XGBoost adds trees in margin/log-odds space and applies sigmoid at the end.
  float margin = -0.2682639594f;

  for (int t = 0; t < XGB_ENSEMBLE_TREES; ++t) {
    const int start = XGB_TREE_OFFSETS[t];
    const int end = XGB_TREE_OFFSETS[t + 1];
    int node = 0;

    while (true) {
      const int g = start + node;
      const int16_t lch = XGB_LEFT[g];

      if (lch < 0) {
        margin += XGB_LEAF_WEIGHT[g];
        break;
      }

      const uint8_t f = XGB_SPLIT_FEATURE[g];
      const float x = features[f];

      // The production inputs are finite. For completeness, missing/NaN
      // values follow XGBoost's default direction encoded by the JSON.
      if (isnan(x)) {
        node = XGB_RIGHT[g] >= 0 ? XGB_RIGHT[g] : XGB_LEFT[g];
      } else if (x < XGB_SPLIT_CONDITION[g]) {
        node = XGB_LEFT[g];
      } else {
        node = XGB_RIGHT[g];
      }

      if (node < 0 || start + node >= end) return false;
    }
  }

  result.margin = margin;
  result.probability = sigmoidStable(margin);
  result.prediction = (result.probability >= 0.5f);
  return true;
}

// ============================================================
// XGB TREE DEBUG
// ============================================================
//
// This performs the SAME traversal as runXGBEnsemble(),
// but prints every decision made by every tree.
//
// It is for diagnostic purposes only.
//
// ============================================================

void runXGBTreeDebug(
    const float features[XGB_ENSEMBLE_FEATURES]
)
{
    Serial.println();
    Serial.println("==============================================");
    Serial.println("          XGB TREE-BY-TREE DEBUG");
    Serial.println("==============================================");

    // --------------------------------------------------------
    // XGBoost base margin
    // --------------------------------------------------------

    float margin = -0.2682639594f;

    int totalLeaves = 0;

    // --------------------------------------------------------
    // Process all 150 trees
    // --------------------------------------------------------

    for (int t = 0; t < XGB_ENSEMBLE_TREES; ++t)
    {
        const int start = XGB_TREE_OFFSETS[t];
        const int end   = XGB_TREE_OFFSETS[t + 1];

        int node = 0;

        // ----------------------------------------------------
        // Traverse this tree
        // ----------------------------------------------------

        while (true)
        {
            const int g = start + node;

            const int16_t lch = XGB_LEFT[g];

            // ------------------------------------------------
            // LEAF NODE
            // ------------------------------------------------

            if (lch < 0)
            {
                const float leafWeight =
                    XGB_LEAF_WEIGHT[g];

                margin += leafWeight;

                Serial.printf(
                    "Tree %3d | GlobalNode %4d | "
                    "LeafWeight %+0.9f\n",
                    t,
                    g,
                    leafWeight
                );

                totalLeaves++;

                break;
            }

            // ------------------------------------------------
            // INTERNAL DECISION NODE
            // ------------------------------------------------

            const uint8_t feature =
                XGB_SPLIT_FEATURE[g];

            const float condition =
                XGB_SPLIT_CONDITION[g];

            const float value =
                features[feature];

            int nextNode;

            // ------------------------------------------------
            // NaN / missing value
            // ------------------------------------------------

            if (isnan(value))
            {
                if (XGB_RIGHT[g] >= 0)
                {
                    nextNode = XGB_RIGHT[g];
                }
                else
                {
                    nextNode = XGB_LEFT[g];
                }
            }

            // ------------------------------------------------
            // XGBoost split
            // ------------------------------------------------

            else if (value < condition)
            {
                nextNode = XGB_LEFT[g];
            }
            else
            {
                nextNode = XGB_RIGHT[g];
            }

            // ------------------------------------------------
            // Print decision
            // ------------------------------------------------

            Serial.printf(
                "Tree %3d | "
                "Node %4d | "
                "F=%2d | "
                "X=%+0.6f | "
                "Split=%+0.6f | "
                "Next=%d\n",

                t,
                g,
                feature,
                value,
                condition,
                nextNode
            );

            // ------------------------------------------------
            // Safety check
            // ------------------------------------------------

            if (nextNode < 0 ||
                start + nextNode >= end)
            {
                Serial.printf(
                    "ERROR: Invalid node in tree %d\n",
                    t
                );

                return;
            }

            node = nextNode;
        }
    }

    // ========================================================
    // FINAL RESULT
    // ========================================================

    const float probability =
        sigmoidStable(margin);

    Serial.println();
    Serial.println("----------------------------------------------");

    Serial.printf(
        "Trees processed   : %d\n",
        totalLeaves
    );

    Serial.printf(
        "Final Margin      : %.9f\n",
        margin
    );

    Serial.printf(
        "Final Probability : %.9f\n",
        probability
    );

    Serial.print("Final Class       : ");

    if (probability >= 0.5f)
    {
        Serial.println("1 / ANOMALY");
    }
    else
    {
        Serial.println("0 / NORMAL");
    }

    Serial.println("----------------------------------------------");
    Serial.println("==============================================");
}
