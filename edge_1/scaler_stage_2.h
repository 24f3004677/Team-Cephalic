// ============================================================
// StandardScaler implementation
// ============================================================

inline void scaleFeatures(
    const float input[27],
    float output[27]
) {
    for (int i = 0; i < 27; i++) {
        output[i] =
            (input[i] - SCALER_MEAN[i])
            / SCALER_SCALE[i];
    }
}


// ============================================================
// Print scaled features
// ============================================================

inline void printScaledFeatures(
    const float scaled[27]
) {
    Serial.println();
    Serial.println("========== SCALED 27 FEATURES ==========");

    for (int i = 0; i < 27; i++) {
        Serial.printf(
            "[%02d] = %.10f\n",
            i,
            scaled[i]
        );
    }

    Serial.println("=========================================");
}

